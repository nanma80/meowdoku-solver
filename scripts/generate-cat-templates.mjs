// Run after deliberately changing the reference artwork, not during normal builds.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { findCandidateCells } from '../src/detection/cells.js';
import { findSquareGrid } from '../src/detection/grid.js';
import { readCellColors } from '../src/detection/colors.js';
import { createSymbolSignature } from '../src/detection/symbols.js';

const require = createRequire(import.meta.url);
const { PNG } = require('pngjs');
const image = PNG.sync.read(
  readFileSync(
    new URL('../screenshots/iphone-08x08-board-01-partial.png', import.meta.url),
  ),
);
const grid = findSquareGrid(findCandidateCells(image, 0.3));
const { colors, palette } = readCellColors(image, grid);
const referenceCats = [
  [0, 3],
  [2, 4],
  [3, 2],
  [4, 5],
  [5, 1],
  [6, 6],
  [7, 0],
];
const templates = referenceCats.map(([row, column]) => {
  const signature = createSymbolSignature(
    image,
    grid[row][column],
    palette[colors[row][column]],
  );
  return (
    '  [\n' +
    signature
      .match(/.{24}/g)
      .map((line) => `    '${line}',`)
      .join('\n') +
    "\n  ].join(''),"
  );
});
const output = [
  '// Generated by scripts/generate-cat-templates.mjs from screenshots/iphone-08x08-board-01-partial.png.',
  '// Each 24 × 24 sample uses dot for background and 0–f for foreground brightness.',
  '// Multiple poses and approximate matching accommodate the animated artwork.',
  'export const CAT_TEMPLATES = [',
  ...templates,
  '];',
  '',
].join('\n');
writeFileSync(new URL('../src/detection/cat-templates.js', import.meta.url), output);
